"""
Configuration loading and shared proxy state.

See config.default.yaml for the config and secrets file formats, with a
worked, test-covered example of every section. How a host's several entries
are matched, and how a credential is bound to the entry that declares it,
is documented in docs/service-presets.md ("How enforcement works"); how
header scrubbing and credential wiring interact on a restricted entry is
covered in that same file's "Credential presets" section.
"""

import collections
import copy
import dataclasses
import hashlib
import json
import re
import threading
from dataclasses import dataclass, field

import yaml

import registries
import services as services_module


@dataclass
class HostConfig:
    allow_response_cookies: list[str] | None = None
    # None means no restriction; a list (even empty) enables filtering


# Structural keys on a `services:` entry that are never a preset-declared
# ScopeFlag -- anything else on the entry must be one, so a typo'd flag name
# (e.g. "wrtie: true") is a hard error instead of a silently-ignored no-op.
_SERVICE_ENTRY_KEYS = frozenset({
    "service", "host", "scope", "unrestricted", "real_value", "fake_value", "allow_host",
    "enabled",
})


@dataclass(frozen=True)
class Credential:
    host: str
    header: str
    real_value: str
    fake_value: str | None = None  # None means inject mode
    preset: str | None = None      # service preset that produced this entry
                                   # (informational, like HostRules.source)


@dataclass(frozen=True)
class HostEntry:
    """One `hosts:` entry (hand-written or generated by a service preset).

    rules is None for an unrestricted entry. A host may carry several
    entries; see AllowlistAddon for how they're matched. credential, if set,
    is brokered only for requests this entry permits (see
    CredentialBrokerAddon).
    """
    rules: registries.HostRules | None = None
    host_config: HostConfig = field(default_factory=HostConfig)
    credential: Credential | None = None


def _expand_secret_string(value: str, secrets: dict) -> str:
    """Expand ${KEY} references in a single string value using the secrets map."""
    def replace(m):
        key = m.group(1)
        if key not in secrets:
            raise KeyError(f"Secret key not found in secrets_file: ${{{key}}}")
        return str(secrets[key])
    return re.sub(r'\$\{([^}]+)\}', replace, value)


def _expand_secret_fields(data: dict, secrets: dict) -> dict:
    """Expand ${KEY} references, but only in the fields documented to carry
    them: `real_value`/`fake_value` on `hosts[].credential` and `services[]`
    entries (see config.default.yaml and docs/service-presets.md -- these
    are the only documented uses of ${KEY}).

    Deliberately *not* a recursive whole-document expansion: every other
    field (host, scope values, ...) is validated against a pattern after
    this step, and a validation failure echoes the offending value back in
    its ValueError message. Expanding those fields too would let a
    `${KEY}` placed somewhere other than real_value/fake_value (e.g.
    `services[].host` or a `scope:` value) turn a routine pattern-mismatch
    error into a verbatim secret leak, in an HTTP response body (the
    management API surfaces ValueError text to the operator) or on stdout
    (Config.load's startup/SIGHUP path). Restricting expansion to the two
    fields that actually need it closes that channel at the root, rather
    than trying to scrub secrets out of error messages after the fact.
    """
    def expand_entry(entry):
        if not isinstance(entry, dict):
            return entry
        new_entry = dict(entry)
        for key in ("real_value", "fake_value"):
            if isinstance(new_entry.get(key), str):
                new_entry[key] = _expand_secret_string(new_entry[key], secrets)
        return new_entry

    new_data = dict(data)
    if isinstance(new_data.get("services"), list):
        new_data["services"] = [expand_entry(e) for e in new_data["services"]]
    if isinstance(new_data.get("hosts"), list):
        new_data["hosts"] = [
            {**e, "credential": expand_entry(e["credential"])}
            if isinstance(e, dict) and "credential" in e else e
            for e in new_data["hosts"]
        ]
    return new_data


def _redact_known_secrets(message: str, secrets: dict) -> str:
    """Scrub any live secret value out of a validation error message.

    Belt and braces for the leak Finding 1 closed at the root (see
    _expand_secret_fields): expansion is now scoped to real_value/fake_value,
    so no other field's pattern-mismatch ValueError should ever carry a
    secret. This is a backstop against a future field growing a ${KEY} use
    without updating _expand_secret_fields to match -- it only redacts
    literal secret values that actually appear in the message, so an
    ordinary validation error (unknown key, bad pattern, missing field, ...)
    is completely unaffected and stays as actionable as before.
    """
    for value in secrets.values():
        if isinstance(value, str) and value and value in message:
            message = message.replace(value, "[REDACTED]")
    return message


def require_bool(container: dict, name: str, default: bool | None = None) -> bool:
    """Read a boolean config/API key strictly.

    Only an actual `True`/`False` is accepted -- never a string ("no",
    "false", "0", ...) or an int (0, 1). YAML happily parses a hand-quoted
    `unrestricted: "no"` as the Python str "no", and a JSON API client can
    send any JSON type for a field; Python's bare `bool(...)` treats any
    non-empty string (including "no" and "false") and any nonzero int as
    truthy. For a key that gates broad access -- `unrestricted`, a service
    scope flag such as `write`/`graphql`, `allow_host` -- that coercion
    silently grants exactly the access the operator (or API caller) meant to
    decline. Being strict here is deliberate, not merely consistent.
    """
    if name not in container:
        if default is None:
            raise ValueError(f"{name!r} is required and must be true or false")
        return default
    value = container[name]
    if not isinstance(value, bool):
        raise ValueError(f"{name!r} must be true or false, got {value!r}")
    return value


def _host_entries(data: dict, section: str = "hosts") -> list:
    """Validate `hosts:` as a list of str-or-dict entries, dicts having a "host" key.

    An entry compiles to a restricted rule set iff it carries a "rules" key;
    otherwise it's unrestricted (a bare string is always unrestricted, since
    there's no mapping to hang a "rules" list off of).
    """
    entries = data.get(section) or []
    if not isinstance(entries, list):
        raise ValueError(f"{section} must be a list, got {type(entries).__name__}")
    for i, item in enumerate(entries):
        if isinstance(item, str):
            continue
        if not isinstance(item, dict) or not isinstance(item.get("host"), str):
            raise ValueError(f"{section}[{i}] must be a string or a mapping with a 'host' key")
        if "credentials" in item:
            raise ValueError(f"{section}[{i}]: unknown key 'credentials' (did you mean 'credential'?)")
        if "credential" in item:
            _parse_credential(item["host"], item["credential"], f"{section}[{i}].credential")
    return entries


_CREDENTIAL_KEYS = frozenset({"header", "real_value", "fake_value"})


def _parse_credential(host: str, raw, where: str) -> Credential:
    """Validate an inline `credential:` mapping on a hosts entry."""
    if not isinstance(raw, dict):
        raise ValueError(f"{where} must be a mapping")
    missing = [k for k in ("header", "real_value") if not raw.get(k)]
    if missing:
        raise ValueError(f"{where} missing required key(s): {', '.join(missing)}")
    unknown = sorted(k for k in raw if k not in _CREDENTIAL_KEYS)
    if unknown:
        raise ValueError(
            f"{where}: unknown key(s) {', '.join(unknown)} "
            f"(the credential's host is its entry's host)"
        )
    return Credential(
        host=host,
        header=raw["header"],
        real_value=raw["real_value"],
        fake_value=raw.get("fake_value"),
    )


def _host_entry(rules, credential, host_config) -> HostEntry:
    """Build a HostEntry, keeping its credential's header alive through the
    entry's own header scrubbing (AllowlistAddon scrubs before
    CredentialBrokerAddon swaps the real value in)."""
    if rules is not None and credential is not None:
        rules = dataclasses.replace(
            rules, request_headers=rules.request_headers | {credential.header.lower()},
        )
    return HostEntry(rules=rules, host_config=host_config, credential=credential)


# Identity of a `services:` entry: (service name, host or None). The
# management API addresses services by the same pair.
ServiceKey = tuple[str, str | None]


@dataclass(frozen=True)
class Config:
    """A complete, validated proxy configuration.

    Built only by Config.load or Config.from_data, which parse the config and
    secrets file exactly once and raise on any invalid section — so a Config
    either exists fully formed or not at all (no partial policy state).
    """

    hosts: dict[str, list[HostEntry]]
    # `enabled: false` services, fully validated and expanded but not in
    # `hosts` -- a temporary enable (ProxyState.temp_services) adds their
    # entries at request time.
    dormant_services: dict[ServiceKey, dict[str, list[HostEntry]]] = field(default_factory=dict)
    management_port: int = 8082
    happy_eyeballs_delay: float = 0.25
    # The config as written (before ${KEY} expansion), for the management
    # API to show and edit -- the fields above are compiled from it.
    raw: dict = field(default_factory=dict, compare=False)
    # sha256 of the file this was loaded from (None: built from data, or the
    # file was missing), to detect edits made on disk since.
    source_digest: str | None = None

    @property
    def credentials(self) -> list[Credential]:
        """Every entry's credential, flattened (for redaction, counts and the
        management API -- brokering itself goes through the matched entry).
        Includes dormant services' credentials, so a disabled service's real
        token is still redacted."""
        host_maps = [self.hosts, *self.dormant_services.values()]
        return [e.credential for hosts in host_maps for entries in hosts.values()
                for e in entries if e.credential is not None]

    @classmethod
    def load(cls, path: str) -> "Config":
        try:
            with open(path, "rb") as f:
                content = f.read()
        except FileNotFoundError:
            print(json.dumps({
                "event": "config_warning",
                "message": f"config file not found: {path}; starting with empty config (deny-all)",
            }))
            return cls.from_data({})
        config = cls.from_data(yaml.safe_load(content) or {})
        return dataclasses.replace(config, source_digest=_digest(content))

    @classmethod
    def from_data(cls, data: dict) -> "Config":
        """Validate an already-parsed config dict (no file I/O beyond secrets_file).

        Lets a caller validate a prospective config (e.g. the management API
        checking a rewritten config.yaml) before persisting it, instead of
        writing first and finding out it doesn't load.
        """
        raw = copy.deepcopy(data)
        secrets = {}
        secrets_path = data.get("secrets_file")
        secrets_missing = False
        if secrets_path:
            try:
                with open(secrets_path) as f:
                    secrets = yaml.safe_load(f) or {}
            except FileNotFoundError:
                # Fine until something references it: the management API
                # creates the file when it stores the first token.
                secrets_missing = True
        try:
            data = _expand_secret_fields(data, secrets)
        except KeyError as e:
            if secrets_missing:
                raise FileNotFoundError(
                    f"secrets_file not found: {secrets_path} ({e.args[0]})"
                ) from None
            raise

        try:
            if "allowed_registries" in data:
                raise ValueError(
                    "allowed_registries was renamed to services; "
                    "move the preset names there (e.g. services: [go, npm])"
                )
            if "allowed_hosts" in data:
                raise ValueError(
                    "allowed_hosts was merged into hosts; "
                    "move entries there unchanged (e.g. hosts: [api.anthropic.com])"
                )
            if "restricted_hosts" in data:
                raise ValueError(
                    "restricted_hosts was merged into hosts; "
                    "move entries there unchanged (each entry keeps its 'rules' list)"
                )

            if "credentials" in data:
                raise ValueError(
                    "credentials moved onto hosts entries; give the entry for each "
                    "credential's host a 'credential:' mapping with its header, "
                    "real_value and (for swap mode) fake_value, e.g. hosts: "
                    "[{host: api.example.com, credential: {header: Authorization, "
                    "real_value: ...}}]"
                )

            host_entries = _host_entries(data)

            # Service presets: each `services` entry expands into host entries
            # (restricted or unrestricted), its brokered credential attached
            # to the entry for the credential's host. Restricted entries strip
            # all response cookies by default:
            # registries don't need them, and Set-Cookie is a session/tracking
            # channel into the sandbox.
            hosts = {}
            dormant_services = {}
            for i, entry in enumerate(data.get("services") or []):
                if isinstance(entry, str):
                    entry = {"service": entry}
                if not isinstance(entry, dict) or not isinstance(entry.get("service"), str):
                    raise ValueError(
                        f"services[{i}] must be a string or a mapping with a 'service' key"
                    )
                name = entry["service"]
                preset = services_module.SERVICE_PRESETS.get(name)
                if preset is None:
                    raise ValueError(
                        f"Unknown service preset {name!r}; "
                        f"available: {sorted(services_module.SERVICE_PRESETS)}"
                    )

                # host_param generalizes the old bare `param_host: bool` -- the
                # entry supplies the key host_param names (currently always
                # "host") and it's checked against host_param.pattern like any
                # other ScopeParam value.
                resolved_host = None
                if preset.host_param:
                    hp = preset.host_param
                    raw_host = entry.get(hp.name)
                    if not isinstance(raw_host, str):
                        raise ValueError(f"services[{i}] ({name}) requires a {hp.name!r}")
                    if not re.fullmatch(hp.pattern, raw_host):
                        raise ValueError(
                            f"services[{i}] ({name}): {hp.name!r} {raw_host!r} "
                            f"does not match the required pattern"
                        )
                    resolved_host = raw_host
                elif "host" in entry:
                    raise ValueError(f"services[{i}] ({name}) does not take a 'host'")

                spec = preset.credential
                cred_host = None
                credential = None
                if spec is None:
                    extra = [k for k in ("real_value", "fake_value") if k in entry]
                    if extra:
                        raise ValueError(
                            f"services[{i}] ({name}) takes no credential; "
                            f"unexpected key(s): {', '.join(extra)}"
                        )
                else:
                    cred_host = spec.on_host or resolved_host
                    missing = [k for k in ("real_value", "fake_value") if not entry.get(k)]
                    if missing:
                        raise ValueError(
                            f"services[{i}] ({name}) missing required key(s): "
                            f"{', '.join(missing)}"
                        )
                    credential = Credential(
                        host=cred_host,
                        header=spec.header,
                        real_value=spec.wrap(entry["real_value"]),
                        fake_value=spec.wrap(entry["fake_value"]),
                        preset=name,
                    )

                # Any entry key beyond the fixed structural ones must be a
                # preset-declared ScopeFlag -- catches a typo'd flag (e.g.
                # "wrtie: true") that would otherwise silently leave a service
                # more (or less) open than the operator intended.
                known_flags = {f.name: f for f in preset.scope_flags}
                unknown_flags = sorted(
                    k for k in entry if k not in _SERVICE_ENTRY_KEYS and k not in known_flags
                )
                if unknown_flags:
                    raise ValueError(
                        f"services[{i}] ({name}): unknown key(s) {', '.join(unknown_flags)}; "
                        f"available flags: {sorted(known_flags)}"
                    )
                flags = {
                    f.name: True for f in preset.scope_flags
                    if f.name in entry and require_bool(entry, f.name, False)
                }
                for f in preset.scope_flags:
                    if flags.get(f.name) and f.unscoped:
                        print(json.dumps({
                            "event": "service_flag_unscoped",
                            "service": name,
                            "flag": f.name,
                            "message": f"{name}: {f.name} defeats scoping ({f.description})",
                        }))

                # preset.hosts carries only static, always-on hosts (package
                # registries; empty for github/gitlab). A preset that declares
                # scope_params must additionally be scoped or explicitly opted
                # out -- this is the control that closes blanket GitHub/GitLab
                # access: no scope and no opt-out is a hard error, not a warning,
                # because a log line among many is too easy to miss here.
                preset_hosts = dict(preset.hosts)
                if preset.scope_params:
                    has_scope = "scope" in entry
                    unrestricted = require_bool(entry, "unrestricted", False)
                    if has_scope and unrestricted:
                        raise ValueError(
                            f"services[{i}] ({name}): 'scope' and 'unrestricted: true' "
                            f"are mutually exclusive"
                        )
                    if not has_scope and not unrestricted:
                        raise ValueError(
                            f"services[{i}] ({name}) must be scoped: set 'scope:' "
                            f"(available params: {sorted(p.name for p in preset.scope_params)}) "
                            f"or 'unrestricted: true' to explicitly opt out of scoping"
                        )
                    if unrestricted:
                        # The explicit, logged opt-out -- every host this entry
                        # could otherwise touch (static preset.hosts, plus the
                        # resolved host_param/credential host) is granted
                        # blanket access instead of a compiled rule set.
                        unrestricted_hosts = set(preset.hosts) | {
                            h for h in (resolved_host, cred_host) if h is not None
                        }
                        for h in unrestricted_hosts:
                            preset_hosts[h] = None
                            print(json.dumps({
                                "event": "service_unrestricted",
                                "service": name,
                                "host": h,
                                "message": f"{name}: unrestricted access granted to {h}",
                            }))
                    else:
                        escaped = preset.build_scope(entry.get("scope"))
                        spec_by_host = preset.scope_template(escaped, flags, resolved_host)
                        for host, rule_spec in spec_by_host.items():
                            preset_hosts[host] = registries.compile_host_rules(rule_spec, source=name)
                elif resolved_host is not None:
                    preset_hosts[resolved_host] = None

                # A credential only ever fires for requests its own entry
                # permits, so "broker the token but don't allowlist its host"
                # would leave it with no entry to fire from.
                if not require_bool(entry, "allow_host", True):
                    raise ValueError(
                        f"services[{i}] ({name}): 'allow_host: false' is no longer "
                        f"supported; a credential is brokered only for requests its "
                        f"own hosts entry permits. To broker this token under a "
                        f"hand-written hosts: entry, give that entry a 'credential:' "
                        f"instead of using this service"
                    )
                if credential is not None and cred_host not in preset_hosts:
                    raise ValueError(
                        f"services[{i}] ({name}): preset produced no entry for its "
                        f"credential's host {cred_host!r}"
                    )
                # A disabled entry is validated and expanded all the same, so
                # enabling it (permanently or temporarily) can't fail later.
                target = hosts
                if not require_bool(entry, "enabled", True):
                    target = dormant_services.setdefault((name, resolved_host), {})
                for host, rules in preset_hosts.items():
                    host_cred = credential if host == cred_host else None
                    target.setdefault(host, []).append(_host_entry(
                        rules, host_cred,
                        HostConfig(allow_response_cookies=[] if rules is not None else None),
                    ))

            # Hand-written `hosts:` entries compile with the same engine and are
            # appended after the preset-generated ones. One naming a host a
            # service preset also covers adds a sibling entry rather than
            # replacing the preset's; see AllowlistAddon for how a host's
            # entries are matched.
            for i, item in enumerate(host_entries):
                if isinstance(item, str):
                    hosts.setdefault(item, []).append(HostEntry())
                    continue
                host = item["host"]
                rules = (registries.compile_host_rules(item, source="config")
                         if "rules" in item else None)
                credential = None
                if "credential" in item:
                    credential = _parse_credential(host, item["credential"], f"hosts[{i}].credential")
                hosts.setdefault(host, []).append(_host_entry(
                    rules, credential,
                    HostConfig(allow_response_cookies=item.get(
                        "allow_response_cookies", [] if rules is not None else None,
                    )),
                ))

            return cls(
                hosts=hosts,
                dormant_services=dormant_services,
                management_port=int(data.get("management_port", 8082)),
                happy_eyeballs_delay=float(data.get("happy_eyeballs_delay", 0.25) or 0),
                raw=raw,
            )
        except ValueError as e:
            raise ValueError(_redact_known_secrets(str(e), secrets)) from None


def _digest(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def _file_digest(path: str) -> str | None:
    try:
        with open(path, "rb") as f:
            return _digest(f.read())
    except FileNotFoundError:
        return None


@dataclass
class ProxyState:
    config_path: str  # path to config YAML, used by reload()
    hosts: dict[str, list[HostEntry]] = field(default_factory=dict)
    credentials: list[Credential] = field(default_factory=list)
    management_port: int = 8082
    dormant_services: dict[ServiceKey, dict[str, list[HostEntry]]] = field(default_factory=dict)
    temp_allows: dict[str, float] = field(default_factory=dict)  # host -> expires_at (epoch)
    temp_services: dict[ServiceKey, float] = field(default_factory=dict)  # -> expires_at (epoch)
    temp_lock: threading.Lock = field(default_factory=threading.Lock)
    deny_log: collections.deque = field(default_factory=lambda: collections.deque(maxlen=1000))
    deny_lock: threading.Lock = field(default_factory=threading.Lock)
    # The applied config as written, and the digest of the file it came from
    # (see Config.raw / Config.source_digest). Everything but loading and
    # writing back reads these, never the file.
    raw_config: dict = field(default_factory=dict)
    config_digest: str | None = None
    # Serializes config changes: reload() and the management API's
    # read-modify-write-apply sequences.
    config_lock: threading.Lock = field(default_factory=threading.Lock)

    def apply(self, config: Config) -> None:
        """Swap in a validated config.

        Replace-not-mutate: each policy field is rebound to a fresh object, so
        readers on other threads see either the old or the new object, never a
        half-updated one. management_port is intentionally not re-applied —
        the API server is already bound; the port is set once at construction.
        """
        self.hosts = dict(config.hosts)
        self.dormant_services = dict(config.dormant_services)
        self.credentials = list(config.credentials)
        self.raw_config = config.raw
        self.config_digest = config.source_digest

    def reload(self) -> None:
        """Re-read the config file and apply it (SIGHUP)."""
        with self.config_lock:
            self.apply(Config.load(self.config_path))

    def config_changed_on_disk(self) -> bool:
        """Whether the config file differs from what was last loaded or
        written -- a hand edit not yet reloaded, which a write would
        otherwise overwrite."""
        return _file_digest(self.config_path) != self.config_digest

    def commit(self, data: dict, config: Config) -> None:
        """Write `data` (already validated as `config`) to the config file
        and apply it. The caller holds config_lock and has checked
        config_changed_on_disk()."""
        content = yaml.safe_dump(data).encode()
        with open(self.config_path, "wb") as f:
            f.write(content)
        self.apply(dataclasses.replace(config, source_digest=_digest(content)))
